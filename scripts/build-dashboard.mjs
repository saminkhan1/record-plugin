import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schedulePath = path.join(repoRoot, "dashboard", "src", "schedule.js");
const pagePath = path.join(repoRoot, "dashboard", "src", "index.js");
const stylePath = path.join(repoRoot, "dashboard", "src", "style.css");
const outputPath = path.join(repoRoot, "dashboard", "dist", "index.js");
const outputStylePath = path.join(repoRoot, "dashboard", "dist", "style.css");

const [scheduleSource, pageSource, styleSource] = await Promise.all([
  readFile(schedulePath, "utf8"),
  readFile(pagePath, "utf8"),
  readFile(stylePath, "utf8"),
]);

if (pageSource.includes("SDK.schedule") || /SDK\.components[^;\n]*ScheduleBuilder/.test(pageSource)) {
  throw new Error("Dashboard source still depends on fork-only Hermes schedule SDK exports");
}

const banner = [
  "/**",
  " * Generated by `npm run build:dashboard`.",
  " * Schedule UI and serialization are plugin-owned to preserve upstream compatibility.",
  " */",
  "",
].join("\n");

await mkdir(path.dirname(outputPath), { recursive: true });
await Promise.all([
  writeFile(outputPath, `${banner}${scheduleSource.trim()}\n\n${pageSource.trim()}\n`, "utf8"),
  writeFile(outputStylePath, `${styleSource.trim()}\n`, "utf8"),
]);
